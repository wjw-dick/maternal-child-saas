export const t = (key) => messages[locale.value]?.[key] ?? messages.zh[key] ?? key
export const isEn = computed(() => locale.value === 'en')

export function setLocale(next) {
  locale.value = next === 'en' ? 'en' : 'zh'
  localStorage.setItem('mc_locale', locale.value)
  document.documentElement.lang = locale.value === 'en' ? 'en' : 'zh-CN'
}

export function toggleLocale() {
  setLocale(locale.value === 'zh' ? 'en' : 'zh')
}

/** 内容字段优先取英文，缺失时回退中文。 */
export function pick(obj, zhKey, enKey) {
  if (!obj) return ''
  if (locale.value === 'en') return obj[enKey] || obj[zhKey] || ''
  return obj[zhKey] || obj[enKey] || ''
}
